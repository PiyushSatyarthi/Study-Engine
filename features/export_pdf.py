"""Export saved papers as PDF (premium only)."""
import os
import tempfile
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import cm
from reportlab.lib import colors
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, HRFlowable
from reportlab.lib.enums import TA_LEFT, TA_CENTER


def generate_export_pdf(user_id: int, papers: list, title: str = "My Saved Papers") -> str:
    """
    Generates a PDF of saved papers.
    Returns the temp file path — caller must delete after sending.
    """
    tmp = tempfile.NamedTemporaryFile(suffix=".pdf", delete=False, prefix=f"export_{user_id}_")
    path = tmp.name
    tmp.close()

    doc = SimpleDocTemplate(
        path, pagesize=A4,
        leftMargin=2*cm, rightMargin=2*cm,
        topMargin=2*cm, bottomMargin=2*cm
    )

    styles = getSampleStyleSheet()

    title_style = ParagraphStyle(
        "Title", parent=styles["Title"],
        fontSize=20, spaceAfter=6, textColor=colors.HexColor("#1a1a2e")
    )
    subtitle_style = ParagraphStyle(
        "Subtitle", parent=styles["Normal"],
        fontSize=10, textColor=colors.grey, spaceAfter=20, alignment=TA_CENTER
    )
    paper_title_style = ParagraphStyle(
        "PaperTitle", parent=styles["Normal"],
        fontSize=12, fontName="Helvetica-Bold",
        textColor=colors.HexColor("#2d6a4f"), spaceAfter=4
    )
    meta_style = ParagraphStyle(
        "Meta", parent=styles["Normal"],
        fontSize=9, textColor=colors.grey, spaceAfter=4
    )
    link_style = ParagraphStyle(
        "Link", parent=styles["Normal"],
        fontSize=9, textColor=colors.HexColor("#0077b6"), spaceAfter=4
    )
    summary_style = ParagraphStyle(
        "Summary", parent=styles["Normal"],
        fontSize=10, spaceAfter=4, leading=14
    )
    note_style = ParagraphStyle(
        "Note", parent=styles["Normal"],
        fontSize=10, textColor=colors.HexColor("#6b4226"),
        backColor=colors.HexColor("#fff3cd"),
        spaceAfter=4, leftIndent=10, rightIndent=10
    )

    story = []

    # Header
    story.append(Paragraph("📚 Study Engine", title_style))
    story.append(Paragraph(title, subtitle_style))
    story.append(Paragraph(f"Total papers: {len(papers)}", subtitle_style))
    story.append(HRFlowable(width="100%", thickness=1, color=colors.HexColor("#dee2e6")))
    story.append(Spacer(1, 16))

    for i, paper in enumerate(papers, 1):
        # Paper number + title
        t = paper.get("title", "Untitled")
        story.append(Paragraph(f"{i}. {t}", paper_title_style))

        # Source + collection
        meta_parts = [f"Source: {paper.get('source', 'unknown').upper()}"]
        if paper.get("collection"):
            meta_parts.append(f"Collection: {paper['collection']}")
        if paper.get("topic"):
            meta_parts.append(f"Topic: {paper['topic']}")
        story.append(Paragraph(" · ".join(meta_parts), meta_style))

        # Link
        story.append(Paragraph(f"🔗 {paper.get('pdf', '')}", link_style))

        # AI summary if available
        if paper.get("ai_summary"):
            story.append(Paragraph(f"<b>AI Summary:</b> {paper['ai_summary']}", summary_style))

        # User note if available
        if paper.get("note"):
            story.append(Paragraph(f"📝 Note: {paper['note']}", note_style))

        story.append(HRFlowable(width="100%", thickness=0.5, color=colors.HexColor("#e9ecef")))
        story.append(Spacer(1, 10))

    # Footer
    story.append(Spacer(1, 10))
    story.append(Paragraph("Generated by Study Engine Bot", subtitle_style))

    doc.build(story)
    return path
